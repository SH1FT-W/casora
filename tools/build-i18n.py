def main() -> int:
    if not os.path.isdir(SRC):
        print("no translation source at %s" % SRC, file=sys.stderr)
        return 1

    tables = {}
    for name in sorted(os.listdir(SRC)):
        if not name.endswith(".json") or name == "en.json":
            continue
        lang = name[: -len(".json")]
        with open(os.path.join(SRC, name), encoding="utf-8") as fh:
            data = json.load(fh)
        tables[lang] = {k: v for k, v in sorted(data.items()) if isinstance(v, str)}

    phrases = {}
    if os.path.isdir(PHRASES):
        for name in sorted(os.listdir(PHRASES)):
            if not name.endswith(".json"):
                continue
            with open(os.path.join(PHRASES, name), encoding="utf-8") as fh:
                data = json.load(fh)
            bad = [p for p in data.get("patterns") or [] if not (isinstance(p, list) and len(p) == 2)]
            if bad:
                # Nicht still verwerfen: zwei verschmolzene Muster gingen sonst unbemerkt verloren.
                raise SystemExit("%s: Muster muss [Regex, Text] sein: %s" % (name, json.dumps(bad[0], ensure_ascii=False)))
            pats = data.get("patterns") or []
            # The runtime takes the first matching pattern: a specific one goes before a general one
            # that also matches its texts ("^Ø von (\\d+) Lampen$" before "^Ø (.+)$").
            try:
                pats = [pats[i] for i in i18n_patterns.order([p[0] for p in pats])]
            except ValueError as e:
                raise SystemExit("%s: %s" % (name, e))
            left = i18n_patterns.shadowed([p[0] for p in pats])
            if left:
                raise SystemExit("%s: pattern %r hides %r (%r)" % ((name,) + left[0]))
            phrases[name[: -len(".json")]] = {
                "exact": {k: v for k, v in sorted((data.get("exact") or {}).items()) if isinstance(v, str)},
                "patterns": pats,
            }

    body = json.dumps(tables, ensure_ascii=False, indent=2, sort_keys=True)
    # The source language (de, a few entries) ships inline; every other language is its own file,
    # fetched by the runtime only when that language is shown.
    inline = {k: v for k, v in phrases.items() if k == SOURCE}
    pbody = json.dumps(inline, ensure_ascii=False, separators=(",", ":"))
    avail = sorted(k for k in phrases if k != SOURCE)

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(RUNTIME % (body, pbody, json.dumps(avail)))
    os.makedirs(OUT_LANG, exist_ok=True)
    for name in os.listdir(OUT_LANG):
        if name.endswith(".json") and name[:-5] not in avail:
            os.remove(os.path.join(OUT_LANG, name))
    for k in avail:
        text = json.dumps(phrases[k], ensure_ascii=False, separators=(",", ":"))
        path = os.path.join(OUT_LANG, k + ".json")
        # Unchanged files keep their time stamp (it is part of the cache ?v=).
        try:
            with open(path, encoding="utf-8") as fh:
                if fh.read() == text:
                    continue
        except OSError:
            pass
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)

    print("wrote %s (%d key table(s): %s; phrases: %s)" % (
        os.path.relpath(OUT, ROOT), len(tables), ", ".join(tables) or "none",
        ", ".join("%s %d+%d" % (k, len(v["exact"]), len(v["patterns"])) for k, v in phrases.items()) or "none"))
    return 0


