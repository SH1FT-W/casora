#!/usr/bin/env python3
"""Compile the dashboard translation tables into a shared frontend script.

Run from the repo root after changing anything under
custom_components/casora/translations/dashboard/:

    python3 tools/build-i18n.py

Two layers:

  • Keys – window._casoraT(key, english, vars) for the Hemma core strings.
    en.json is the key reference, not a shipped table: every call site carries
    its English default inline. Only the other languages are emitted.

  • Phrases – Casora's own cards and popups are written in German. For every
    other language the rendered text is translated on the way out (button-card
    output and window.casoraTr), from phrases/<lang>.json:
        {"exact": {"<German>": "<translation>"},
         "patterns": [["^<regex on the German text>$", "… {1} …"]]}
    Patterns are written in any order; the build puts a specific pattern before a general one
    that would also match its text (tools/i18n_patterns.py), since the runtime takes the first match.
    A language without its own table falls back to English. Text that looks
    German but has no entry is collected: casoraTrMissing() in the console.
"""

